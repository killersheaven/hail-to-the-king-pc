#!/usr/bin/env python3
"""Writes recomp/sh4_table.h, the SH-4 decode table of tools/sh4.py for the C recompiler
(recomp/recomp.c), in the same order sh4.decode() tries it. usage: gen_decode_table.py"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
import sh4
K = ["", "bra", "bsr", "braf", "bsrf", "jmp", "jsr", "rts", "rte", "bt", "bf", "bts", "bfs", "trapa"]
F = ["0", "n", "nm", "md", "nd4", "nmd", "d", "d12", "nd8", "i", "ni", "bank"]
out = ["/* generated by tools/gen_decode_table.py from tools/sh4.py: do not edit */",
       "/* mask, match, mnemonic, format, kind, delay slot; most specific mask first */"]
for mask, match, mn, fmt, kind, delay in sh4.T:
    out.append('{0x%04X, 0x%04X, "%s", F_%s, K_%s, %d},' % (mask, match, mn, fmt, kind.upper() or "NONE", int(delay)))
open(os.path.join(here, "..", "recomp", "sh4_table.h"), "w").write("\n".join(out) + "\n")
print("%d entries" % len(sh4.T))
